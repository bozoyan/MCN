class PropPreset {
  const PropPreset(
    this.name,
    this.group,
    this.size,
    this.minimum, {
    this.origin = 'bottom_center',
    this.direction = '+Y up; +Z front',
    this.supportHeights = const [],
  });
  final String name, group, origin, direction;
  final List<double> size, minimum, supportHeights;
  String get geometry => 'prop.$name.v1';
  String get asset => 'assets/director/models/props/$name.glb';
  List<double> get defaultPosition => [0, minimum[1] < 0 ? -minimum[1] : 0, 0];
  List<double> get maximum => [
    for (var i = 0; i < 3; i++) minimum[i] + size[i],
  ];
}

