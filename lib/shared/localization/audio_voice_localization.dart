String localizedAudioVoiceName(
  BuildContext context,
  String voiceId, {
  int presetIndex = -1,
}) {
  final key = _audioVoiceNameKeys[voiceId];
  if (key != null) {
    return context.t(key);
  }
  if (presetIndex >= 0) {
    return context.t(
      LocaleKeys.audioVoiceUnnamedPreset,
      namedArgs: {'number': '${presetIndex + 1}'},
    );
  }
  return voiceId;
}
