  return context.t(_keys[label] ?? LocaleKeys.directorOperationFailed);
}

/// 新建工程默认机位的名称，与「添加机位」同样使用「预设名_序号」。
String defaultCameraName(BuildContext context) => trArgs(
  context,
  'camera_name',
  {'preset': tr(context, 'default_camera'), 'index': '1'},
);

String trArgs(BuildContext context, String label, Map<String, String> args) =>
    context.t(
      _keys[label] ?? LocaleKeys.directorOperationFailed,
      namedArgs: args,
    );
